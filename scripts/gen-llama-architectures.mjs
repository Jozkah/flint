#!/usr/bin/env node
// Regenerates web-app/src/lib/llamaArchitectures.generated.ts: the model
// architectures (`general.architecture`) the bundled llama.cpp can load, read
// from `LLM_ARCH_NAMES` in src/llama-arch.cpp at the pinned tag.
//
//   node scripts/gen-llama-architectures.mjs [path/to/llama-arch.cpp]
//
// Without a path the file is fetched from github.com/ggml-org/llama.cpp at the
// tag in src-tauri/plugins/tauri-plugin-llamacpp/build.rs. A test fails when
// that tag moves without this being run again.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const BUILD_RS = resolve(ROOT, 'src-tauri/plugins/tauri-plugin-llamacpp/build.rs')
const OUT = resolve(ROOT, 'web-app/src/lib/llamaArchitectures.generated.ts')

export function pinnedTag(buildRs) {
  const match = /LLAMA_CPP_TAG:\s*&str\s*=\s*"(b\d+)"/.exec(buildRs)
  if (!match) throw new Error('LLAMA_CPP_TAG not found in build.rs')
  return match[1]
}

/** The names in the `LLM_ARCH_NAMES` map, in source order. */
export function parseArchitectures(source) {
  const start = source.indexOf('LLM_ARCH_NAMES = {')
  if (start === -1) throw new Error('LLM_ARCH_NAMES not found')
  const end = source.indexOf('\n};', start)
  const body = source.slice(start, end)
  const names = [...body.matchAll(/\{\s*LLM_ARCH_[A-Z0-9_]+\s*,\s*"([^"]+)"\s*\}/g)].map((m) => m[1])
  if (names.length < 50) throw new Error(`only ${names.length} architectures parsed`)
  return names
}

export function render(tag, names) {
  return `// Generated by scripts/gen-llama-architectures.mjs from llama.cpp ${tag}
// (src/llama-arch.cpp, LLM_ARCH_NAMES). Do not edit; run the script again when
// the bundled engine changes.

export const LLAMA_CPP_ARCHITECTURES_TAG = '${tag}'

export const LLAMA_CPP_ARCHITECTURES: readonly string[] = [
${names.map((n) => `  '${n}',`).join('\n')}
]
`
}

async function main() {
  const tag = pinnedTag(readFileSync(BUILD_RS, 'utf8'))
  const local = process.argv[2]
  const source = local
    ? readFileSync(local, 'utf8')
    : await fetch(`https://raw.githubusercontent.com/ggml-org/llama.cpp/${tag}/src/llama-arch.cpp`).then((r) => {
        if (!r.ok) throw new Error(`llama.cpp ${tag}: HTTP ${r.status}`)
        return r.text()
      })
  const names = parseArchitectures(source)
  writeFileSync(OUT, render(tag, names))
  console.log(`${names.length} architectures for ${tag} -> ${OUT}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
