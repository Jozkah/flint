#!/bin/bash
# Stop at the first failure: without this a failed step (such as the bun copy
# below) still ended in a repackaged AppImage and exit 0 (#157).
set -euo pipefail

ARCH="${ARCH:-"$(uname -m)"}"
case "$ARCH" in
  x86_64|amd64)        ARCH="x86_64"  ;;
  i386|i486|i586|i686) ARCH="i386"    ;;
  arm64|aarch64)       ARCH="aarch64" ;;
  arm*)                ARCH="armhf"   ;;
esac

APPIMAGETOOL="./.cache/build-tools/appimagetool"
RELEASE_CHANNEL=${RELEASE_CHANNEL:-"stable"}

# appimagetool is itself an AppImage, so it mounts itself through FUSE, which
# the hosted runners no longer provide. This runs outside shim-linuxdeploy.sh,
# so it needs its own copy of the fallback.
export APPIMAGE_EXTRACT_AND_RUN=1

# A release tag and its SHA-256, not the moving `continuous` build: this binary
# runs in the release job and repackages the shipped AppImage, so a changed or
# swapped download must stop the build instead of being run (F6-012).
APPIMAGETOOL_VER="1.9.1"
case "$ARCH" in
  x86_64)  APPIMAGETOOL_ASSET="x86_64";  APPIMAGETOOL_SHA256="ed4ce84f0d9caff66f50bcca6ff6f35aae54ce8135408b3fa33abfc3cb384eb0" ;;
  aarch64) APPIMAGETOOL_ASSET="aarch64"; APPIMAGETOOL_SHA256="f0837e7448a0c1e4e650a93bb3e85802546e60654ef287576f46c71c126a9158" ;;
  armhf)   APPIMAGETOOL_ASSET="armhf";   APPIMAGETOOL_SHA256="42b61cba5495d8aaf418a5c9a015a49b85ad92efabcbd3c341f1540440e4e23d" ;;
  i386)    APPIMAGETOOL_ASSET="i686";    APPIMAGETOOL_SHA256="7ad9ff47c203aae0149b18f6df9e3018b2e2f470ea644a0413e3ded39e9e3bdb" ;;
  *) echo "No pinned appimagetool for architecture $ARCH."; exit 1 ;;
esac

mkdir -p ./.cache/build-tools
wget "https://github.com/AppImage/appimagetool/releases/download/${APPIMAGETOOL_VER}/appimagetool-${APPIMAGETOOL_ASSET}.AppImage" -O "${APPIMAGETOOL}" || { echo "Failed to download appimagetool."; exit 1; }
echo "${APPIMAGETOOL_SHA256}  ${APPIMAGETOOL}" | sha256sum -c - || { echo "appimagetool does not match its pinned SHA-256; refusing to run it."; rm -f "${APPIMAGETOOL}"; exit 1; }
chmod +x "${APPIMAGETOOL}"

if [ "${RELEASE_CHANNEL}" != "stable" ]; then
    APP_DIR=./src-tauri/target/release/bundle/appimage/Flint-${RELEASE_CHANNEL}.AppDir
else
    APP_DIR=./src-tauri/target/release/bundle/appimage/Flint.AppDir
fi

# bundle additional resources in the AppDir without pulling in their dependencies
cp ./src-tauri/resources/bin/bun "$APP_DIR/usr/bin/bun" || { echo "Failed to copy the bun sidecar into $APP_DIR."; exit 1; }

# tauri-cli before 2.11.4 (tauri-apps/tauri#15596) links .DirIcon to the icon's
# absolute build-host path, which dangles inside the mounted AppImage and which
# AppImage catalogs reject. Re-point it relative to the AppDir root.
DIR_ICON="$APP_DIR/.DirIcon"
if [[ "$(readlink "$DIR_ICON")" == /* ]]; then
    ln -sfn "$(basename "$(readlink "$DIR_ICON")")" "$DIR_ICON"
fi
if [ ! -f "$DIR_ICON" ] || [[ "$(readlink "$DIR_ICON")" == /* ]]; then
    echo ".DirIcon in $APP_DIR is missing or not relative to the AppDir."
    exit 1
fi

# The host's Vulkan loader and NVIDIA driver have to be the ones that run; a copy
# from the build host crashed every model load (janhq/jan#9173). shim-linuxdeploy.sh
# excludes them, so finding one here means that exclusion stopped applying.
HOST_LIBS=$(find "$APP_DIR" \( -name 'libvulkan.so*' -o -name 'libcuda.so*' \) 2>/dev/null)
if [ -n "$HOST_LIBS" ]; then
    echo "$APP_DIR bundles libraries that must come from the user's system:"
    echo "$HOST_LIBS"
    exit 1
fi

# remove appimage generated by tauri build
# A glob, not `ls | grep | head -1`: exactly one image must be there, or a stale
# one from an earlier build would be repackaged instead (F6-012).
shopt -s nullglob
IMAGES=(./src-tauri/target/release/bundle/appimage/*.AppImage)
shopt -u nullglob
if [ "${#IMAGES[@]}" -ne 1 ]; then
    echo "Expected exactly one AppImage from tauri build, found ${#IMAGES[@]}: ${IMAGES[*]:-}"
    exit 1
fi
APP_IMAGE="${IMAGES[0]}"
echo "$APP_IMAGE"
rm -f "$APP_IMAGE"

# repackage appimage with additional resources
"${APPIMAGETOOL}" "$APP_DIR" "$APP_IMAGE"
