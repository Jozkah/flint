// The ACL for the app's own commands, derived from `src/lib.rs` at build time.
//
// Without an app manifest Tauri lets every local window call every
// `#[tauri::command]` the app registers, whatever its capability file says.
// With one, an app command is refused unless a capability grants its
// `allow-<command>` permission -- every command, not only the listed ones, so
// the list has to be complete. It is therefore read from the
// `generate_handler!` lists rather than kept by hand, and two permission sets
// are generated from it (see `permission_sets_toml`).
//
// Shared by `build.rs` and a unit test in `src/lib.rs` (`#[path]` module), so
// keep it free of dependencies.

/// Commands only the main window and chat windows may call. The logs and
/// system-monitor windows load the same front end (and its providers), so
/// they keep every other command; these are the destructive or
/// trust-granting ones that only a user action in Settings, Cowork or Studio
/// reaches, never anything that runs on mount.
pub const MAIN_WINDOW_ONLY: &[&str] = &[
    "factory_reset",
    "change_app_data_folder",
    "install_jan_cli",
    "uninstall_jan_cli",
    "archive_restore",
    "agent_worktree_discard",
    "agent_checkpoint_restore",
    "agent_skill_write",
    "agent_skill_hub_import",
    "agent_skill_enabled_set",
    "capture_desktop_preview",
    "launch_claude_code_with_config",
    "remote_set_config",
    "remote_start_pairing",
    "remote_confirm_pairing",
    "remote_revoke_device",
    "diffusion_install_engine",
];

/// The permission set every command belongs to (main and chat windows).
pub const ALL_COMMANDS_SET: &str = "app-commands";
/// The set for the logs and system-monitor windows.
pub const AUX_WINDOW_SET: &str = "aux-window-commands";

/// Every command name registered in `lib_rs`: each entry of the
/// `generate_handler!` list inside the `invoke_commands_with_extras!` macro,
/// and of every call to that macro. A command is named by the last segment of
/// its path, which is what the front end invokes.
pub fn registered_commands(lib_rs: &str) -> Vec<String> {
    let mut names: Vec<String> = Vec::new();
    let mut inside = false;
    for raw in lib_rs.lines() {
        let line = raw.split("//").next().unwrap_or("").trim();
        if line.ends_with("generate_handler![") || line.ends_with("invoke_commands_with_extras![") {
            inside = true;
            continue;
        }
        if !inside {
            continue;
        }
        if line.starts_with(']') || line.starts_with("$(") {
            inside = false;
            continue;
        }
        if line.is_empty() || line.starts_with("#[") {
            continue;
        }
        let path = line.trim_end_matches(',').trim();
        if path.is_empty() || !path.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == ':') {
            continue;
        }
        if let Some(name) = path.rsplit("::").next() {
            if !name.is_empty() && !names.iter().any(|n| n == name) {
                names.push(name.to_string());
            }
        }
    }
    names
}

/// The permission Tauri generates for `command` (`allow-` plus kebab case).
pub fn allow_permission(command: &str) -> String {
    format!("allow-{}", command.replace('_', "-"))
}

/// A permission file with the two sets: every command, and every command but
/// [`MAIN_WINDOW_ONLY`].
pub fn permission_sets_toml(commands: &[String]) -> String {
    let list = |pick: &dyn Fn(&str) -> bool| {
        commands
            .iter()
            .filter(|c| pick(c))
            .map(|c| format!("  \"{}\",\n", allow_permission(c)))
            .collect::<String>()
    };
    format!(
        "# Generated by build.rs from src/lib.rs. Do not edit.\n\n\
         [[set]]\nidentifier = \"{ALL_COMMANDS_SET}\"\n\
         description = \"Every app command (main and chat windows).\"\n\
         permissions = [\n{}]\n\n\
         [[set]]\nidentifier = \"{AUX_WINDOW_SET}\"\n\
         description = \"Every app command except the main-window-only ones (logs and system-monitor windows).\"\n\
         permissions = [\n{}]\n",
        list(&|_| true),
        list(&|c| !MAIN_WINDOW_ONLY.contains(&c)),
    )
}
